export function developmentScene(index: number, status: ConversationStatus) {
  const scene = scenes[index % scenes.length];
  const recent = [...scene.recent];
  if (status !== "needs-reply") {
    recent.splice(-2, 2, ...scene[status]);
  }
  return {
    ...scene,
    recent: recent.map<DevelopmentTurn>((text, position) => ({
      direction:
        position % 2 === 0 || (status === "needs-reply" && position === 7)
          ? "incoming"
          : "outgoing",
      body: { type: "text", text },
    })),
    preview: recent[recent.length - 1],
  };
}

export function developmentEarlierTurns(count: number): DevelopmentTurn[] {
  return Array.from({ length: count }, (_, position) => ({
    direction: position % 2 === 0 ? "incoming" : "outgoing",
    body: {
      type: "text",
      text: earlierExchanges[
        Math.floor(position / 2) % earlierExchanges.length
      ][position % 2],
    },
  }));
}
